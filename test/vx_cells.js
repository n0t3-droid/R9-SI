// The furniture, facade and tech models of the first packs (voxfurn / voxhome / voxlife / voxtech …) used to be built
// at every start of every thread — 135 models, half a second on a fast machine, two on a small one, in the main
// thread and in every worker. Now they register from a table of their occupied cells and average colour
// (src/shared/voxcells.js) and build themselves on first use like the late packs. The table must say exactly what
// the build makes — the cells name the block's 'part' states, and saved worlds store those state ids:
//   bash test/wt_run.sh vx_cells.js            check every model against its build
//   bash test/wt_run.sh vx_cells.js --write    regenerate src/shared/voxcells.js after a model's build changed
const fs = require('fs');
const V = require('./load_shared.js');
const VM = V.VM, R = V.R;
const FILE = require('path').join(__dirname, '..', 'src', 'shared', 'voxcells.js');   // also right from a copy in .tmp_tests (wt_run.sh)
const eager = VM.DEFS.filter(d => !d.o.late && !d.o.lazy);
const built = {};
let ms = 0;
for (const d of eager) { const t0 = performance.now(); const m = VM.compile(d.name, d.o); ms += performance.now() - t0; built[d.name] = [m.col, m.parts.map(p => [p.px, p.py, p.pz])]; }
if (process.argv.includes('--write')) {
  const lines = Object.keys(built).map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(built[n])}`);
  const src = `// ============================================================================
// Generated by test/vx_cells.js --write — the occupied cells (block parts, in build order) and the average colour of
// every model of the first packs, so they register without being built: the build runs on first use (voxmodel.js
// lazyModel). The cells name the 'part' states of the block, so they must match the build exactly: run the test
// after changing a model, and --write when it says so.
// ============================================================================
VR.VM_CELLS = {
${lines.join(',\n')}
};
`;
  fs.writeFileSync(FILE, src);
  console.log('wrote', FILE, Object.keys(built).length, 'models');
  process.exit(0);
}
let fail = 0;
const check = (ok, what) => { console.log((ok ? 'OK   ' : 'FAIL ') + what); if (!ok) fail++; };
const table = V.VM_CELLS || {};
check(Object.keys(table).length === eager.length, `the table holds every model of the first packs (${Object.keys(table).length} of ${eager.length})`);
let lazyN = 0, cellsOk = 0, colOk = 0, partsOk = 0, builtOk = 0, bad = [];
for (const d of eager) {
  const m = VM.MODELS[d.name], want = built[d.name], have = table[d.name];
  if (!m) { bad.push(d.name + ' (not registered)'); continue; }
  if (m.lazy) lazyN++;
  const sameCells = have && JSON.stringify(have[1]) === JSON.stringify(want[1]);
  if (sameCells) cellsOk++; else bad.push(d.name + ' (cells differ from the build — run --write)');
  if (have && have[0] === want[0]) colOk++; else bad.push(d.name + ' (colour differs — run --write)');
  if (JSON.stringify(m.parts.map(p => [p.px, p.py, p.pz])) === JSON.stringify(want[1])) partsOk++;
  // the lazy build makes what the table says
  VM.materialize(m);
  const scan = VM.scanParts(m).map(p => [p.px, p.py, p.pz]);
  if (JSON.stringify(scan) === JSON.stringify(want[1]) && m.col === want[0] && m.vox > 0) builtOk++; else bad.push(d.name + ' (built model differs)');
  // the block's part states: one per cell, in table order
  const t = R.byName[d.name];
  if (!t || !t.has('part') || t.props[t.propIndex.part].n !== want[1].length) bad.push(d.name + ' (part states)');
}
check(lazyN === eager.length, `all ${eager.length} register lazily, none is built at start (${lazyN})`);
check(cellsOk === eager.length && colOk === eager.length, 'the table matches the build of every model (cells and colour)');
check(partsOk === eager.length && builtOk === eager.length, 'every lazy model has the table\'s parts and builds exactly them');
if (bad.length) console.log('     ' + bad.slice(0, 10).join('\n     '));
// the full-face masks (which neighbour faces a part culls) come out as an eager build of the same model gives them:
// every facing and part of every table model, painted from the independently built copy
{
  const VX = V.VX, PRESENT = VX.PRESENT, GLASS = VX.GLASS;
  let states = 0, same = 0, full = 0; const wrong = [];
  for (const d of eager) {
    const t = R.byName[d.name], m = VM.compile(d.name, d.o); if (!t) continue;
    const NN = m.res, GR = VX.gridFor(NN), IX = NN === 32 ? VX.I32 : NN === 16 ? VX.I16 : VX.I;
    for (let st = t.base; st < t.base + t.nstates; st++) {
      const f = t.get(st, 'facing'), part = t.get(st, 'part');
      VM.paintPart(m, m.parts[part], f);
      let mask = 0;
      for (let dd = 0; dd < 6; dd++) {
        let ok = true;
        for (let a = 0; a < NN && ok; a++) for (let b = 0; b < NN; b++) {
          const x = dd === 0 ? NN - 1 : dd === 1 ? 0 : a, y = dd === 2 ? NN - 1 : dd === 3 ? 0 : (dd < 2 ? a : b), z = dd === 4 ? NN - 1 : dd === 5 ? 0 : b;
          const v = GR[IX(x, y, z)]; if (!(v & PRESENT) || (v & GLASS)) { ok = false; break; }
        }
        if (ok) mask |= 1 << dd;
      }
      states++; if (mask) full++;
      if (VX.full(st) === mask) same++; else if (wrong.length < 5) wrong.push(`${d.name} state ${st}: ${VX.full(st)} vs ${mask}`);
    }
  }
  check(same === states, `the full-face masks of all ${states} states of the table models (${full} with a full face) are those of an eager build`);
  if (wrong.length) console.log('     ' + wrong.join('\n     '));
}
console.log(`     building all ${eager.length} models takes ${ms.toFixed(0)} ms — now paid only for the ones a thread really meets`);
console.log(fail ? `FAILED ${fail}` : 'ALL OK');
process.exit(fail ? 1 : 0);
